"""
Benchmark validation: how well do the policy-simulator presets reproduce the
*character* of their real-world archetypes?

This is deliberately honest. The agent-based model is a stylised mechanism
sandbox, NOT a calibrated reproduction of any city. These tests assert the
QUALITATIVE SIGNATURES each preset is supposed to capture, and the companion
report (generated by report_benchmarks.py) quantifies the deviation in plain
numbers so a reader can see exactly where the analogy holds and where it
breaks.

What each archetype is claimed to capture:

  Tokyo  : supply-driven affordability. Heavy construction + building
           depreciation should yield LOWER burden, LOWER overburden and a
           LOWER price-to-income than baseline. It does NOT attempt to
           reproduce the 1990s asset bubble and 20-year price collapse —
           the ABM has no speculative-bubble mechanism, so that part of
           "Tokyo" is explicitly out of scope (see report).

  Vienna : decommodified affordability via a large public/limited-profit
           housing sector + holding taxes. Should yield the LOWEST burden
           and overburden of the presets. Caveat: real Vienna also has LOW
           ownership (~22%); the preset does not reproduce that tenure
           structure (it actually raises ownership), so the match is on
           AFFORDABILITY, not tenure mix.

  Swiss  : there is intentionally NO Swiss policy preset. The Swiss model
           (interest-only, ownership-rare, flat real prices) is represented
           in the PERSONAL comparator as a scenario kind, validated
           separately in test_finance_comparator.py. Asserting a Swiss
           "preset" in the ABM would be inventing a benchmark that doesn't
           exist, so we don't.

Run just these:  pytest tests/test_benchmarks.py -v
"""
import os
import sys

import pytest

sys.path.insert(0, os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "backend"))

from simulator import PRESETS, PolicyConfig, run_simulation  # noqa: E402


def _run_preset(name: str, years: int = 50, seed: int = 42) -> dict:
    """Run a named preset and return its final-year + trajectory signature."""
    p = PRESETS[name]
    cfg = PolicyConfig(
        max_loan_years=p["max_loan_years"],
        max_ltv=p["max_ltv"],
        construction_rate=p["construction_rate"],
        public_share=p["public_share"],
        depreciation=p["depreciation"],
    )
    h = run_simulation(cfg, years=years, n_households=2000,
                        n_properties=1800, seed=seed)
    final = h[-1]
    prices = [x["median_price"] for x in h]
    peak = max(prices)
    return {
        "homeownership": final["homeownership_rate"],
        "burden": final["housing_burden_median"],
        "overburdened": final["overburdened_pct"],
        "price_to_income": final["price_to_income"],
        "peak_price": peak,
        "final_price": prices[-1],
        "drop_from_peak": (peak - prices[-1]) / peak if peak else 0.0,
        "history": h,
    }


# ---------------------------------------------------------------------------
# Baseline anchor
# ---------------------------------------------------------------------------

def test_baseline_runs_and_is_plausible():
    """Baseline should produce sane, in-range numbers (sanity anchor for the
    relative comparisons below)."""
    b = _run_preset("baseline")
    assert 0.20 <= b["homeownership"] <= 0.85
    assert 0.05 <= b["burden"] <= 0.60
    assert 0.0 <= b["overburdened"] <= 0.60
    assert 1.0 <= b["price_to_income"] <= 12.0


# ---------------------------------------------------------------------------
# Tokyo: supply-driven affordability vs baseline
# ---------------------------------------------------------------------------

def test_tokyo_is_more_affordable_than_baseline():
    """The defining claim: Tokyo-style supply + depreciation lowers the
    housing burden, the overburden rate, AND price-to-income vs baseline."""
    base = _run_preset("baseline")
    tok = _run_preset("tokyo")
    assert tok["burden"] < base["burden"], (
        f"Tokyo burden {tok['burden']:.3f} should be < baseline "
        f"{base['burden']:.3f}")
    assert tok["overburdened"] < base["overburdened"]
    assert tok["price_to_income"] < base["price_to_income"]


def test_tokyo_does_not_claim_to_reproduce_the_bubble():
    """Honesty guard: the ABM has no speculative-bubble mechanism, so the
    Tokyo preset must NOT be expected to show a 1990s-style boom then a
    large multi-decade real-price collapse. We assert the ABM stays
    monotone-ish (no >25% peak-to-final crash), which documents the
    limitation rather than hiding it."""
    tok = _run_preset("tokyo")
    assert tok["drop_from_peak"] < 0.25, (
        "If this ever fails, the ABM has developed crash dynamics and the "
        "Tokyo write-up in the report should be revisited.")


# ---------------------------------------------------------------------------
# Vienna: decommodified affordability
# ---------------------------------------------------------------------------

def test_vienna_has_lowest_burden_of_the_presets():
    """Vienna's large public sector + holding taxes should give it the
    lowest housing burden and overburden among baseline/tokyo/vienna."""
    base = _run_preset("baseline")
    tok = _run_preset("tokyo")
    vie = _run_preset("vienna")
    assert vie["burden"] < base["burden"]
    assert vie["burden"] <= tok["burden"] + 0.03, (
        "Vienna should be at least as affordable as Tokyo on burden "
        "(within a small tolerance)")
    assert vie["overburdened"] < base["overburdened"]
    assert vie["overburdened"] <= tok["overburdened"] + 0.02


def test_vienna_tenure_caveat_is_documented_not_asserted():
    """Real Vienna has LOW ownership (~22%). The preset does NOT reproduce
    that — it raises ownership instead. We assert the KNOWN deviation so the
    test suite itself records the limitation: if ownership ever drops below
    baseline here, the report's caveat would need rewriting."""
    base = _run_preset("baseline")
    vie = _run_preset("vienna")
    # Documented reality of the model: Vienna preset RAISES ownership.
    assert vie["homeownership"] >= base["homeownership"], (
        "The report states the Vienna preset matches affordability, NOT "
        "Vienna's low-ownership tenure structure. This test pins that "
        "known deviation so it can't silently change.")


# ---------------------------------------------------------------------------
# Swiss: explicitly NOT an ABM preset
# ---------------------------------------------------------------------------

def test_no_swiss_policy_preset_exists():
    """The Swiss model is a personal-comparator scenario kind, not an ABM
    policy. Asserting a Swiss preset would invent a benchmark. This test
    documents that design decision."""
    assert "swiss" not in PRESETS
    assert "switzerland" not in PRESETS


# ---------------------------------------------------------------------------
# Determinism: benchmarks must be reproducible
# ---------------------------------------------------------------------------

@pytest.mark.parametrize("name", ["baseline", "tokyo", "vienna"])
def test_preset_is_deterministic(name):
    """Same preset + seed must give identical numbers run-to-run, otherwise
    the benchmark report is not trustworthy."""
    a = _run_preset(name, seed=7)
    b = _run_preset(name, seed=7)
    assert a["burden"] == b["burden"]
    assert a["homeownership"] == b["homeownership"]
    assert a["price_to_income"] == b["price_to_income"]
